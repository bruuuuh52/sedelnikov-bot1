import asyncio
from datetime import datetime
from bot.database import get_session, init_db
from bot.database.crud import create_interview_slot
from bot.database.models import InterviewSlot
from sqlalchemy import delete


# Русские названия месяцев и дней недели (для вывода в консоль)
RU_MONTHS = {
    1: "января", 2: "февраля", 3: "марта", 4: "апреля",
    5: "мая", 6: "июня", 7: "июля", 8: "августа",
    9: "сентября", 10: "октября", 11: "ноября", 12: "декабря"
}

RU_WEEKDAYS = {
    0: "понедельник", 1: "вторник", 2: "среда",
    3: "четверг", 4: "пятница", 5: "суббота", 6: "воскресенье"
}


def format_date_ru(dt: datetime) -> str:
    """Форматирует дату на русском: '6 октября, вторник, 17:30'"""
    day = dt.day
    month = RU_MONTHS[dt.month]
    weekday = RU_WEEKDAYS[dt.weekday()]
    time = dt.strftime("%H:%M")
    return f"{day} {month}, {weekday}, {time}"


async def main():
    await init_db()
    
    async with get_session() as session:
        
        # ---------------------------------------------------------
        # 🗑 СНАЧАЛА УДАЛЯЕМ ВСЕ СТАРЫЕ СЛОТЫ
        # ---------------------------------------------------------
        await session.execute(delete(InterviewSlot))
        await session.commit()
        print("[OK] Все старые слоты удалены")
        
        # ---------------------------------------------------------
        # 🎯 ЗДЕСЬ НАСТРАИВАЕШЬ ДАТЫ И КОЛИЧЕСТВО МЕСТ (ОКТЯБРЬ 2026)
        # ---------------------------------------------------------
        # Формат: datetime(ГОД, МЕСЯЦ, ДЕНЬ, ЧАС, МИНУТА)
        # Месяц: 10 = октябрь
        slots_data = [
            (datetime(2026, 10, 20, 17, 30), 6),  # 20 октября, вторник, 17:30 — 6 мест
            (datetime(2026, 10, 21, 17, 30), 6),  # 21 октября, среда, 17:30 — 6 мест
            (datetime(2026, 10, 22, 17, 30), 6),  # 22 октября, четверг, 17:30 — 6 мест
            (datetime(2026, 10, 23, 17, 30), 6),  # 23 октября, пятница, 17:30 — 6 мест
            (datetime(2026, 10, 24, 12, 30), 6),  # 24 октября, суббота, 12:30 — 6 мест
            (datetime(2026, 10, 24, 17, 30), 6),  # 24 октября, суббота, 17:30 — 6 мест
            (datetime(2026, 10, 25, 12, 30), 6),  # 25 октября, воскресенье, 12:30 — 6 мест
            (datetime(2026, 10, 25, 17, 30), 6),  # 25 октября, воскресенье, 17:30 — 6 мест
        ]

        # ---------------------------------------------------------
        # 🔄 НЕ МЕНЯЙ ЭТОТ ЦИКЛ — он создаёт слоты в базе
        # ---------------------------------------------------------
        for date, max_slots in slots_data:
            slot = await create_interview_slot(session, date, max_slots)
            
            # Красивый вывод с русскими названиями
            date_str = format_date_ru(date)
            
            print(f"[OK] Создан слот: {date_str} — {max_slots} мест (ID: {slot.id})")

        await session.commit()
        
        print("\n[OK] Готово! Все слоты октября записаны в базу.")
        print("[INFO] Кандидаты увидят эти даты на русском языке.")


if __name__ == "__main__":
    asyncio.run(main())